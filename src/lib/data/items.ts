import { DAY, HOUR, ago, fromNow } from "../clock";
import type { Bounty, CategoryId, IdentifyingDetail, Item, ItemType, PetDetails } from "../types";

/* ─────────────────────────────────────────────────────────────
   Seed listings. Authored compactly, expanded by `make()`.
   Image files live in /public/images — until a photo is dropped in,
   <ItemImage> shows a labelled placeholder ("Image of …").
   ───────────────────────────────────────────────────────────── */

interface Seed {
  slug: string;
  type: ItemType;
  title: string;
  description: string;
  category: CategoryId;
  locationId: string;
  note?: string;
  /** ISO local-time of when it was lost/found */
  at: string;
  timeLabel: string;
  /** milliseconds before the demo "now" */
  posted: number;
  owner: string;
  images: string[];
  details?: [string, string, boolean?][];
  pet?: PetDetails;
  bounty?: { amount: number; expiresInDays: number };
  stats?: [likes: number, comments: number, views: number];
  resolved?: { agoMs: number; with: string };
}

const bounties: Bounty[] = [];

function make(s: Seed): Item {
  const id = `itm_${s.slug.replace(/-/g, "_")}`;
  let bountyId: string | undefined;
  if (s.bounty) {
    bountyId = `bty_${s.slug.replace(/-/g, "_")}`;
    bounties.push({
      id: bountyId,
      itemId: id,
      amount: s.bounty.amount,
      currency: "SGD",
      status: "open",
      createdAt: ago(s.posted),
      expiresAt: fromNow(s.bounty.expiresInDays * DAY),
    });
  }
  const details: IdentifyingDetail[] = (s.details ?? []).map(([label, value, hidden]) => ({ label, value, hidden }));
  const [likes, comments, views] = s.stats ?? [3, 1, 80];
  return {
    id,
    slug: s.slug,
    type: s.type,
    status: s.resolved ? "resolved" : "active",
    moderation: "ok",
    title: s.title,
    description: s.description,
    category: s.category,
    images: s.images.map((label, i) => ({ file: `${s.slug}-${i + 1}.jpg`, label })),
    locationId: s.locationId,
    locationNote: s.note,
    occurredAt: `${s.at}+08:00`,
    timeLabel: s.timeLabel,
    postedAt: ago(s.posted),
    ownerId: s.owner,
    bountyId,
    details,
    pet: s.pet,
    likes,
    comments,
    views,
    resolvedAt: s.resolved ? ago(s.resolved.agoMs) : undefined,
    resolvedWithUserId: s.resolved?.with,
  };
}

