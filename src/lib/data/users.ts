import type { AreaId, User, UserStats } from "../types";

type Seed = {
  id: string;
  handle: string;
  name: string;
  hue: number;
  homeArea: AreaId;
  since: string;
  bio: string;
  tagline?: string;
  rating: number;
  reviews: number;
  verified?: boolean;
  stats: Partial<UserStats>;
  /** allTime / season / month */
  pts: [number, number, number];
  badges?: string[];
  areaPoints: Partial<Record<AreaId, number>>;
  role?: User["role"];
};

const baseStats: UserStats = {
  itemsFound: 0,
  itemsLost: 0,
  itemsReturned: 0,
  bountyReturns: 0,
  areasHelped: 0,
  helpedThisMonth: 0,
  electronicsReturned: 0,
  responseMinutes: 180,
};

function make(s: Seed): User {
  return {
    id: s.id,
    handle: s.handle,
    name: s.name,
    hue: s.hue,
    bio: s.bio,
    tagline: s.tagline,
    homeArea: s.homeArea,
    memberSince: `${s.since}T09:00:00+08:00`,
    verified: s.verified ?? true,
    profileComplete: true,
    rating: s.rating,
    reviews: s.reviews,
    stats: { ...baseStats, ...s.stats },
    points: { allTime: s.pts[0], season: s.pts[1], month: s.pts[2] },
    badges: s.badges ?? [],
    areaPoints: s.areaPoints,
    role: s.role ?? "member",
  };
}

